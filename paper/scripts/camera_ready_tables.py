#!/usr/bin/env python3
"""Generate the LaTeX tables added or changed for the camera-ready version.

Reads result JSONs written by the compute_* scripts and the rebuttal analyses, and writes one
.tex fragment per table to paper/outputs/camera_ready/. Each fragment is the tabular body that
is pasted into ML4H_2026___CARE/main.tex (the Overleaf source is kept self-contained).

Inputs (all regenerated by ./reproduce.sh):
  outputs/fst_summarizer_resplit_cis.json      summarizer transfer (Table K)
  outputs/fst_sample_complexity.json           calibration-set size (App. B)
  outputs/fst_alt_judge_results.json           Gemini / Qwen judges (App. H, Table 12)
  outputs/fst_external_scorer_results.json     external scorers under LTT-FST (Tables 11, 12)
  outputs/external_scorer_results.json         Max-F1 columns of Table 11 (unchanged procedure)
  rebuttal/r3_q1_label_agreement.json          error-class agreement + confusion matrices (App. A)
  rebuttal/r4_human_ground_truth.json          thresholds scored against clinician labels (App. A)
  rebuttal/r2_privds_redundancy.json           copy-forward (App. D)
  rebuttal/r3_q4_grouping.json                 patient-overlap impact (App. D)
  ../experiments/ltt_split_ordering/outputs/results_round0.json   ordering / deploy-rule ablation
"""
import json
from pathlib import Path

import numpy as np

PAPER = Path(__file__).resolve().parents[1]
OUT = PAPER / "outputs"
REB = PAPER / "rebuttal"
DST = OUT / "camera_ready"
DST.mkdir(exist_ok=True)
DS = [("ACI_Bench", "ACI-Bench"), ("MIMIC_IV_BHC", "MIMIC-BHC"), ("MIMIC_III_CXR", "MIMIC-CXR"),
      ("PRIV_DS", "Priv-DS"), ("SumPubMed", "SumPubMed")]
ALPHA = 0.15


def load(p):
    p = Path(p)
    return json.load(open(p)) if p.exists() else None


def boot(v, seed=42, B=10000):
    v = np.asarray(v, float) * 100
    m = np.random.default_rng(seed).choice(v, (B, len(v))).mean(1)
    return v.mean(), np.percentile(m, 2.5), np.percentile(m, 97.5)


def ci(v):
    m, lo, hi = boot(v)
    return f"{m:.1f}{{\\tiny [{lo:.1f},{hi:.1f}]}}"


def write(name, lines):
    (DST / f"{name}.tex").write_text("\n".join(lines) + "\n")
    print(f"wrote {name}.tex")


# --------------------------------------------------------------------------- summarizer transfer
def summarizer_transfer():
    d = load(OUT / "fst_summarizer_resplit_cis.json")
    if d is None:
        return
    rows = []
    names = [("llama", "Llama-3.3-70B"), ("gemini-2.5-pro", "Gemini 2.5 Pro"),
             ("gpt5", "GPT-5$^\\ddagger$"), ("gpt5-mini", "GPT-5-mini$^\\ddagger$")]
    main = load(OUT / "resplit_cis_fst.json")
    for ds, lab in DS[:2]:
        for k, (sk, sname) in enumerate(names):
            if sk == "llama":
                # primary pipeline numbers (Table 2)
                r = main[ds] if main and ds in main else None
                if r is None:
                    continue
                per = r["per_resplit"]
                fv = [x["fact_viol"] for x in per]; ov = [x["omit_viol"] for x in per]
                fwl = np.mean([x["fact_wl_pct"] for x in per]); owl = np.mean([x["omit_wl_pct"] for x in per])
                fr = np.mean([x["fact_recall"] for x in per]) * 100; orc = np.mean([x["omit_recall"] for x in per]) * 100
            else:
                key = f"{ds}__{sk}"
                if key not in d:
                    continue
                per = d[key]["per_resplit"]
                fv = [x["fact_viol"] for x in per]; ov = [x["omit_viol"] for x in per]
                fwl = np.mean([x["fact_wl_pct"] for x in per]); owl = np.mean([x["omit_wl_pct"] for x in per])
                fr = np.mean([x["fact_recall"] for x in per]) * 100; orc = np.mean([x["omit_recall"] for x in per]) * 100
            first = lab if k == 0 else ""
            shade = "\\rowcolor{gray!6}\n" if k % 2 == 1 else ""
            rows.append(f"{shade}{first} & {sname} & {ci(fv)} & {fwl:.1f} & {fr:.1f} & {ci(ov)} & {owl:.1f} & {orc:.1f} \\\\")
        rows.append("\\midrule")
    write("summarizer_transfer", rows[:-1])


# --------------------------------------------------------------------------- calibration-set size
def sample_size():
    d = load(OUT / "fst_sample_complexity.json")
    if d is None:
        return
    rows = []
    for ds, lab in DS:
        res = {r["n_sub"]: r for r in d[ds]["results"]}
        cells = []
        for n in (15, 25, 50, 75, 100):
            r = res.get(n)
            cells.append("--" if r is None else f"{r['omit_violation_mean']*100:.1f} / {r['omit_workload_mean']:.1f}")
        rows.append(f"{lab} & " + " & ".join(cells) + " \\\\")
    write("sample_size", rows)


# --------------------------------------------------------------------------- ordering ablation
def ordering_ablation():
    d = load(PAPER.parent / "experiments" / "ltt_split_ordering" / "outputs" / "results_round0.json")
    if d is None:
        return
    rows = []
    for _, lab in DS:
        r = d["results"][lab]
        cell = lambda m: (f"{r[m]['viol_mean']*100:.1f} / {r[m]['workload_mean']:.1f} / "
                          f"{r[m]['frac_resplits_viol_gt_alpha']*100:.0f}")
        rows.append(f"{lab} & {cell('LTT τ+γ (last)')} & {cell('LTT τ+γ (min-WL)')} & {cell('LTT split-order')} \\\\")
    write("ordering_ablation", rows)


# --------------------------------------------------------------------------- clinician labels
def clinician_labels():
    d = load(REB / "r4_human_ground_truth.json")
    if d is None:
        return
    rows = []
    labs = ["Oracle (GPT-5)", "Clinician 1", "Clinician 2"]
    for ds in ("ACI-Bench", "MIMIC-BHC", "MIMIC-CXR"):
        b = d["normalized"][ds]["by_labeler"]
        hr = " / ".join(f"{b[l]['hall_recall']*100:.0f}\\%" for l in labs)
        dv = " / ".join(f"{b[l]['hall_doc_violation']*100:.0f}" for l in labs) + "\\%"
        om = " / ".join(f"{b[l]['omit_frac_loss']*100:.1f}" for l in labs) + "\\%"
        star = "$^\\ast$" if ds == "MIMIC-CXR" else ""
        rows.append(f"{ds} & {hr} & {dv} & {om}{star} \\\\")
    write("clinician_labels", rows)


# --------------------------------------------------------------------------- confusion matrices
def confusion():
    d = load(REB / "r3_q1_label_agreement.json")
    if d is None:
        return
    order = [("hallucination (FACT=0)", "Hallucination"), ("important (IMP=1)", "Important"),
             ("not covered (COV=0)", "Not covered"), ("omission (IMP=1 & COV=0)", "Omission")]
    rows = []
    for ds in ("ACI-Bench", "MIMIC-BHC", "MIMIC-CXR"):
        tasks = d[ds]["tasks"]
        for i, (tk, tname) in enumerate(order):
            key = tk if tk in tasks else next(k for k in tasks if k.split(" ")[0] == tk.split(" ")[0])
            t = tasks[key]
            c = lambda x: f"{x['tp']}/{x['fp']}/{x['fn']}/{x['tn']}"
            first = f"\\multirow{{4}}{{*}}{{{ds}}}" if i == 0 else ""
            rows.append(f"{first} & {tname} & {t['n']} & {c(t['oracle_vs_a1'])} & {c(t['oracle_vs_a2'])} & {c(t['hh'])} \\\\")
        rows.append("\\midrule")
    write("confusion", rows[:-1])


# --------------------------------------------------------------------------- alternative judges
def alt_judges():
    d = load(OUT / "fst_alt_judge_results.json")
    if d is None:
        return
    lines = []
    for k, v in d.items():
        s = v["summary"]
        lines.append(f"% {k}: hall V={s['fact_viol']['mean']*100:.1f} flagged={s['fact_wl']['mean']:.1f} "
                     f"({s['fact_wl_pct']['mean']:.1f}%) rec={s['fact_recall']['mean']*100:.1f} | "
                     f"omit V={s['omit_viol']['mean']*100:.1f} flagged={s['omit_wl']['mean']:.1f} "
                     f"({s['omit_wl_pct']['mean']:.1f}%) rec={s['omit_recall']['mean']*100:.1f}")
    write("alt_judges_summary", lines)


# --------------------------------------------------------------------------- external scorers
def external_scorers():
    fst = load(OUT / "fst_external_scorer_results.json")
    old = load(OUT / "external_scorer_results.json")
    if fst is None:
        return
    names = [("nli_embed", "NLI (DeBERTa)"), ("embed_only", "Embed (BERT)"), ("alignscore", "AlignScore")]
    t11, t12 = [], []

    def pm(per, m):
        v = np.array([x[m] for x in per]) * 100
        return v.mean(), 1.96 * v.std(ddof=1) / np.sqrt(len(v))

    def maxf1(ds, sc, m):
        r = (old or {}).get(f"{ds}__{sc}")
        if not r:
            return None
        if "per_resplit" not in r:  # older cache: summary mean/std only (100 resplits)
            s = r["summary"].get(f"maxf1_{m}")
            return None if s is None else (s["mean"] * 100, 1.96 * s["std"] * 100 / np.sqrt(100))
        v = np.array([x["maxf1"][m] for x in r["per_resplit"]]) * 100
        return v.mean(), 1.96 * v.std(ddof=1) / np.sqrt(len(v))

    def cell(mh, bold_if_above=False):
        m, h = mh
        lo = m - h
        if bold_if_above and lo > ALPHA * 100:
            return f"\\textbf{{{m:.1f}}}$^\\dagger${{\\scriptsize $\\pm${h:.1f}}}"
        return f"{m:.1f}{{\\scriptsize $\\pm${h:.1f}}}"

    for ds, lab in DS:
        for i, (sc, sname) in enumerate(names):
            key = f"{ds}__{sc}"
            if key not in fst:
                t11.append(f"% missing {key}")
                continue
            per = fst[key]["per_resplit"]
            first = lab if i == 0 else ""
            mf = maxf1(ds, sc, "fact_viol"); mo = maxf1(ds, sc, "omit_viol")
            t11.append(f"{first} & {sname} & {cell(pm(per,'fact_viol'))} & "
                       f"{cell(mf, True) if mf else '--'} & {cell(pm(per,'omit_viol'))} & "
                       f"{cell(mo, True) if mo else '--'} \\\\")
            owl = np.mean([x["omit_wl"] for x in per]) if "omit_wl" in per[0] else None
            owlp = np.mean([x["omit_wl_pct"] for x in per])
            orc = np.mean([x["omit_recall"] for x in per]) * 100
            t12.append(f"% {lab} {sname}: omission flagged {owl:.1f} ({owlp:.1f}\\%) recall {orc:.1f}"
                       if owl is not None else f"% {lab} {sname}: omission flagged ({owlp:.1f}\\%) recall {orc:.1f}")
        t11.append("\\midrule")
    write("external_scorers_validity", t11[:-1])
    write("external_scorers_efficiency_omission", t12)


if __name__ == "__main__":
    for f in (summarizer_transfer, sample_size, ordering_ablation, clinician_labels, confusion,
              alt_judges, external_scorers):
        f()
