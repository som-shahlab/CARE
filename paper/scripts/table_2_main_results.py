#!/usr/bin/env python3
"""Table 2: Main Results.

Generates the core results table with both controllers across all datasets.
All point estimates (violation, workload, recall) are resplit means over
100 random 70/30 cal/test resplits (Angelopoulos-style). The bracketed 95% CI
on each violation rate is a bootstrap confidence interval on the *mean* (10,000
resamples, seed 42), matching the convention used in Table 3 and the external-
scorer table. This characterizes the uncertainty of the reported mean, which is
the quantity the CRC guarantee bounds (E[violation] <= alpha). The wider
2.5-97.5 percentile *spread* of per-resplit violation rates (how much a single
calibration draw varies) is reported separately and is not a confidence interval.

Requires: resplit_cis_fst.json (generated by merge_resplit_cis_fst.py).
The omission controller is LTT-FST (tau+gamma ordering); factuality is the
unchanged 1D scalar CRC controller.
"""
import json
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from pathlib import Path
from care.config import DATASETS, PAPER_OUTPUT_DIR as OUTPUT_DIR, get_phase4_results

RESPLIT_CI_PATH = OUTPUT_DIR / "resplit_cis_fst.json"

# Match Table 3 / external-scorer convention exactly.
BOOTSTRAP_ITERS = 10000
BOOTSTRAP_SEED = 42


def bootstrap_mean_ci(values, iters=BOOTSTRAP_ITERS, seed=BOOTSTRAP_SEED):
    """95% bootstrap CI on the MEAN of the per-resplit values (in %)."""
    rng = np.random.default_rng(seed)
    arr = np.asarray(values, dtype=float)
    n = len(arr)
    idx = rng.integers(0, n, size=(iters, n))
    means = arr[idx].mean(axis=1)
    return float(np.percentile(means, 2.5)), float(np.percentile(means, 97.5))


def load_results():
    if not RESPLIT_CI_PATH.exists():
        print(f"ERROR: {RESPLIT_CI_PATH} not found. Run compute_resplit_cis.py first.")
        return []

    resplit_cis = json.load(open(RESPLIT_CI_PATH))

    rows = []
    for dataset, meta in DATASETS.items():
        rs = resplit_cis.get(dataset)
        if rs is None or len(rs.get("per_resplit", [])) == 0:
            print(f"WARNING: {dataset} has no resplit data, skipping")
            continue

        s = rs["summary"]
        n_test = rs["n_test"]
        per_resplit = rs["per_resplit"]

        def ci_mean(metric):
            """95% bootstrap CI on the mean, computed from per-resplit values."""
            vals = [pr[metric] * 100 for pr in per_resplit if metric in pr]
            if not vals:
                return None
            return bootstrap_mean_ci(vals)

        def spread(metric):
            """2.5-97.5 percentile spread of per-resplit values (NOT a CI)."""
            v = s.get(metric, {})
            if "ci_lower" in v and "ci_upper" in v:
                return (v["ci_lower"] * 100, v["ci_upper"] * 100)
            return None

        rows.append({
            "label": meta["label"],
            "n_test": n_test,
            # Factuality (all from resplit means)
            "fact_viol": s["fact_viol"]["mean"] * 100,
            "fact_ci": ci_mean("fact_viol"),
            "fact_spread": spread("fact_viol"),
            "fact_wl": s["fact_wl"]["mean"],
            "fact_wl_pct": s["fact_wl_pct"]["mean"],
            "fact_recall": s["fact_recall"]["mean"] * 100,
            # Omission (all from resplit means)
            "omit_viol": s["omit_viol"]["mean"] * 100,
            "omit_ci": ci_mean("omit_viol"),
            "omit_spread": spread("omit_viol"),
            "omit_wl": s["omit_wl"]["mean"],
            "omit_wl_pct": s["omit_wl_pct"]["mean"],
            "omit_recall": s["omit_recall"]["mean"] * 100,
        })

    return rows


def fmt_ci(val, ci):
    if ci is None:
        return f"{val:.1f}"
    return f"{val:.1f}$_{{[{ci[0]:.1f},{ci[1]:.1f}]}}$"


def generate_latex(rows):
    lines = []
    lines.append(r"\begin{table*}[t]")
    lines.append(r"\centering")
    lines.append(r"\small")
    lines.append(r"\caption{Main results at $\alpha=0.15$, averaged over 100 random 70/30 cal/test resplits. "
                 r"Both controllers satisfy the finite-sample CRC guarantee (mean violation $\le \alpha$). "
                 r"Flagged shows the mean number of sentences flagged per document (and \% of total), a proxy for review effort. "
                 r"Brackets denote a 95\% bootstrap confidence interval on the \emph{mean} violation rate across resplits.}")
    lines.append(r"\label{tab:main-results}")
    lines.append(r"\begin{tabular}{ll ccc ccc}")
    lines.append(r"\toprule")
    lines.append(r"& & \multicolumn{3}{c}{\textbf{Hallucination}} & \multicolumn{3}{c}{\textbf{Omission}} \\")
    lines.append(r"\cmidrule(lr){3-5} \cmidrule(lr){6-8}")
    lines.append(r"Dataset & $N_{\text{test}}$ & Violation\% & Flagged & Recall\% & Violation\% & Flagged & Recall\% \\")
    lines.append(r"\midrule")

    for r in rows:
        fact_viol = fmt_ci(r["fact_viol"], r["fact_ci"])
        omit_viol = fmt_ci(r["omit_viol"], r["omit_ci"])

        lines.append(
            f"{r['label']} & {r['n_test']} & "
            f"{fact_viol} & {r['fact_wl']:.1f} ({r['fact_wl_pct']:.1f}\\%) & {r['fact_recall']:.1f} & "
            f"{omit_viol} & {r['omit_wl']:.1f} ({r['omit_wl_pct']:.1f}\\%) & {r['omit_recall']:.1f} \\\\"
        )

    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    lines.append(r"\end{table*}")
    return "\n".join(lines)


def generate_text(rows):
    lines = ["Main Results (α=0.15, 100 resplits)", "=" * 80]
    def fmt(ci):
        return f"[{ci[0]:.1f},{ci[1]:.1f}]" if ci else "n/a"
    for r in rows:
        lines.append(f"\n{r['label']} (n_test={r['n_test']})")
        lines.append(f"  Fact: viol={r['fact_viol']:.1f}%  CI-mean={fmt(r['fact_ci'])}  "
                     f"resplit-spread={fmt(r['fact_spread'])}  "
                     f"wl={r['fact_wl']:.1f} ({r['fact_wl_pct']:.1f}%), recall={r['fact_recall']:.1f}%")
        lines.append(f"  Omit: viol={r['omit_viol']:.1f}%  CI-mean={fmt(r['omit_ci'])}  "
                     f"resplit-spread={fmt(r['omit_spread'])}  "
                     f"wl={r['omit_wl']:.1f} ({r['omit_wl_pct']:.1f}%), recall={r['omit_recall']:.1f}%")
    return "\n".join(lines)


def render_table_png(rows, out_path):
    """Render the main results table as a clean PNG image."""
    headers = [
        "Dataset", "N_test",
        "F-Viol%", "F-Flagged", "F-Recall%",
        "O-Viol%", "O-Flagged", "O-Recall%",
    ]
    cell_data = []
    for r in rows:
        fact_ci_str = (f" [{r['fact_ci'][0]:.1f},{r['fact_ci'][1]:.1f}]"
                       if r["fact_ci"] else "")
        omit_ci_str = (f" [{r['omit_ci'][0]:.1f},{r['omit_ci'][1]:.1f}]"
                       if r["omit_ci"] else "")
        cell_data.append([
            r["label"],
            str(r["n_test"]),
            f"{r['fact_viol']:.1f}{fact_ci_str}",
            f"{r['fact_wl']:.1f} ({r['fact_wl_pct']:.1f}%)",
            f"{r['fact_recall']:.1f}",
            f"{r['omit_viol']:.1f}{omit_ci_str}",
            f"{r['omit_wl']:.1f} ({r['omit_wl_pct']:.1f}%)",
            f"{r['omit_recall']:.1f}",
        ])

    fig, ax = plt.subplots(figsize=(14, 0.6 + 0.4 * len(cell_data)))
    ax.axis("off")
    ax.set_title("Table 2: Main Results (\u03b1=0.15)", fontsize=13, fontweight="bold", pad=12)

    table = ax.table(
        cellText=cell_data,
        colLabels=headers,
        cellLoc="center",
        loc="center",
    )
    table.auto_set_font_size(False)
    table.set_fontsize(9)
    table.scale(1.0, 1.5)

    for j in range(len(headers)):
        cell = table[0, j]
        cell.set_facecolor("#4472C4")
        cell.set_text_props(color="white", fontweight="bold")

    for i in range(len(cell_data)):
        for j in range(len(headers)):
            cell = table[i + 1, j]
            if i % 2 == 0:
                cell.set_facecolor("#D9E2F3")
            else:
                cell.set_facecolor("#FFFFFF")

    fig.savefig(out_path, bbox_inches="tight", dpi=200, facecolor="white")
    plt.close(fig)


if __name__ == "__main__":
    rows = load_results()

    print(generate_text(rows))
    print()

    latex = generate_latex(rows)
    out_path = OUTPUT_DIR / "table_2_main_results.tex"
    out_path.write_text(latex)
    print(f"Saved: {out_path}")

